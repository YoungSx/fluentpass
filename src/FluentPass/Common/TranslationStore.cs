        public static Dictionary<string, string> GetDictionary(string languageCode)
        {
            if (string.IsNullOrEmpty(languageCode)) return ZhStrings;

            string normalized = languageCode.ToLowerInvariant().Trim();
            if (normalized.StartsWith("zh-tw") || normalized.StartsWith("zh-hk") || normalized.StartsWith("zh-mo") || normalized.Contains("hant"))
            {
                return ZhTwStrings;
            }
            if (normalized.StartsWith("zh"))
            {
                return ZhStrings;
            }
            if (normalized.StartsWith("ja"))
            {
                return JaStrings;
            }
            if (normalized.StartsWith("ko"))
            {
                return KoStrings;
            }
            if (normalized.StartsWith("ru"))
            {
                return RuStrings;
            }
            if (normalized.StartsWith("es"))
            {
                return EsStrings;
            }

            return EnStrings;
        }

        public static Dictionary<string, string> GetFallbackDictionary(string languageCode)
        {
            if (string.IsNullOrEmpty(languageCode)) return EnStrings;

            string normalized = languageCode.ToLowerInvariant().Trim();
            if (normalized.StartsWith("zh-tw") || normalized.StartsWith("zh-hk") || normalized.StartsWith("zh-mo") || normalized.Contains("hant"))
            {
                return ZhStrings;
            }

            return EnStrings;
        }

        public static string Get(string languageCode, string key)
        {
            if (string.IsNullOrEmpty(key)) return string.Empty;

            var primary = GetDictionary(languageCode);
            if (primary.TryGetValue(key, out var val))
            {
                return val;
            }

            var fallback = GetFallbackDictionary(languageCode);
            if (fallback.TryGetValue(key, out var fallbackVal))
            {
                return fallbackVal;
            }

            return key;
        }
    }
